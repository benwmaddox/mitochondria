"""Writes runtime/unicase.c: Unicode's case mappings for lower() and upper(), from Python's unicodedata (the full mappings, as
Ruby's String#downcase and #upcase use them: 'İ' lowers to 'i̇', 'ß' uppers to 'SS'; no context, so a final sigma lowers to σ).
Run: python tools/unicase.py (Python's Unicode version is written into the file)."""
import sys, unicodedata

def table(name, f):
    cps, offs, out = [], [0], bytearray()
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        m = f(c)
        if m != c:
            cps.append(cp)
            out += m.encode('utf-8')
            offs.append(len(out))
    lines = [f'static const u32 uc_{name}_cp[{len(cps)}] = {{']
    for i in range(0, len(cps), 16):
        lines.append('    ' + ', '.join(str(x) for x in cps[i:i + 16]) + ',')
    lines.append('};')
    lines.append(f'static const u32 uc_{name}_off[{len(offs)}] = {{')
    for i in range(0, len(offs), 16):
        lines.append('    ' + ', '.join(str(x) for x in offs[i:i + 16]) + ',')
    lines.append('};')
    lines.append(f'static const u8 uc_{name}_bytes[{max(len(out), 1)}] = {{')
    for i in range(0, len(out), 24):
        lines.append('    ' + ', '.join(str(x) for x in out[i:i + 24]) + ',')
    lines.append('};')
    lines.append(f'#define UC_{name.upper()}_N {len(cps)}')
    return '\n'.join(lines) + '\n'

src = f'''/* Unicode case mappings (generated by tools/unicase.py from Unicode {unicodedata.unidata_version}): for each code point above ASCII whose
   lower (upper) case differs, sorted, the UTF-8 of what it becomes. ASCII is mapped in place. */
''' + table('lower', str.lower) + table('upper', str.upper)
open('runtime/unicase.c', 'w', encoding='utf-8', newline='\n').write(src)
print('unicode', unicodedata.unidata_version, len(src), 'bytes')
